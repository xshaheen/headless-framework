namespace Headless.OpenApi;

/// <summary>
/// Problem details schema for the 400 validation-problem responses of endpoints that declare
/// <c>HttpValidationProblemDetails</c>, such as <c>ProducesValidationProblem()</c> or the .NET <c>AddValidation()</c>
/// endpoint filter.
/// </summary>
/// <remarks>
/// It does not derive from <see cref="HeadlessProblemDetails"/>: the native validation problem carries no
/// <c>detail</c>, and its errors are plain messages rather than error descriptors. The Headless normalization still
/// adds the diagnostics members.
/// </remarks>
public sealed class BadRequestValidationProblemDetails
{
    /// <summary>A URI reference that identifies the problem type (RFC 7807 <c>type</c>).</summary>
    public required string Type { get; init; }

    /// <summary>A short, human-readable summary of the problem type (RFC 7807 <c>title</c>).</summary>
    public required string Title { get; init; }

    /// <summary>The HTTP status code generated by the origin server (RFC 7807 <c>status</c>).</summary>
    public required int Status { get; init; }

    /// <summary>A human-readable explanation specific to this occurrence, when one was supplied.</summary>
    public string? Detail { get; init; }

    /// <summary>The request path of this occurrence (RFC 7807 <c>instance</c>).</summary>
    public required string Instance { get; init; }

    /// <summary>The validation messages keyed by the name of the member that failed.</summary>
    public required Dictionary<string, List<string>> Errors { get; init; }

    /// <summary>The distributed trace identifier for correlating this error across services.</summary>
    public required string TraceId { get; init; }

    /// <summary>The application build version at the time the error occurred.</summary>
    public required string BuildNumber { get; init; }

    /// <summary>The source-control commit hash at the time the error occurred.</summary>
    public required string CommitNumber { get; init; }

    /// <summary>The UTC timestamp at which the error response was produced.</summary>
    public required DateTimeOffset Timestamp { get; init; }
}
