// Prints TypeScript definitions for every operation of the server's OpenAPI document: one entry per operation id,
// with its argument type, its result type, and whether the operation is live (carries x-headless-live).
//
// Usage: node tools/gen-client.mjs <base-url> > api.generated.d.ts
//
// The document is the only source. Routes come from the server's Map calls and shapes from its schemas; a real
// project would use an OpenAPI generator for the shapes and read x-headless-live the way this script does.

const base = process.argv[2];

if (!base) {
  console.error("Usage: node tools/gen-client.mjs <base-url>");
  process.exit(2);
}

const document = await (await fetch(`${base}/openapi/v1.json`)).json();
const used = new Set();

function toType(schema, indent = "") {
  if (schema === undefined || schema === true) return "unknown";

  if (schema.$ref) {
    const name = schema.$ref.split("/").pop();
    used.add(name);

    return name;
  }

  if (schema.oneOf) return [...new Set(schema.oneOf.map(option => toType(option, indent)))].join(" | ");
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(" | ");

  const types = [schema.type ?? "object"].flat();

  // The server also reads a number from a JSON string, so its schema lists both; a client sends the number.
  const numeric = types.includes("integer") || types.includes("number");

  return types
    .filter(type => !(type === "string" && numeric))
    .map(type => {
      switch (type) {
        case "integer":
        case "number":
          return "number";
        case "string":
        case "boolean":
        case "null":
          return type;
        case "array":
          return `Array<${toType(schema.items, indent)}>`;
        case "object":
          return toObject(schema, indent);
        default:
          return "unknown";
      }
    })
    .join(" | ");
}

function toObject(schema, indent) {
  const required = new Set(schema.required ?? []);

  // A property with a default may be left out of a request even though the server always sends it.
  const fields = Object.entries(schema.properties ?? {}).map(([name, property]) => {
    const optional = !required.has(name) || property.default !== undefined;

    return `${indent}  ${name}${optional ? "?" : ""}: ${toType(property, indent + "  ")};`;
  });

  return fields.length === 0 ? "Record<string, never>" : `{\n${fields.join("\n")}\n${indent}}`;
}

function argumentsOf(item, operation) {
  const parameters = [...(item.parameters ?? []), ...(operation.parameters ?? [])].filter(
    parameter => parameter.in === "path" || parameter.in === "query"
  );
  const fields = parameters.map(
    parameter => `    ${parameter.name}${parameter.required ? "" : "?"}: ${toType(parameter.schema, "    ")};`
  );
  const body = operation.requestBody?.content?.["application/json"]?.schema;
  const parts = [];

  if (fields.length > 0) parts.push(`{\n${fields.join("\n")}\n  }`);
  if (body) parts.push(toType(body, "  ").replace(/ \| null$/, ""));

  return parts.length === 0 ? "Record<string, never>" : parts.join(" & ");
}

function resultOf(operation) {
  const success = Object.keys(operation.responses ?? {})
    .filter(status => status.startsWith("2"))
    .sort()[0];
  const schema = operation.responses?.[success]?.content?.["application/json"]?.schema;

  return schema ? toType(schema, "  ") : "void";
}

const entries = [];

for (const [path, item] of Object.entries(document.paths ?? {})) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const operation = item[method];

    if (!operation?.operationId) continue;

    const live = operation["x-headless-live"];
    const name = operation.operationId[0].toLowerCase() + operation.operationId.slice(1);
    const note = live ? ` (live: ${live.mediaTypes.join(", ")})` : "";

    entries.push(
      `  /** ${method.toUpperCase()} ${path}${note} */`,
      `  ${name}: Operation<${argumentsOf(item, operation)}, ${resultOf(operation)}, ${live !== undefined}>;`
    );
  }
}

const lines = [
  "// Generated by tools/gen-client.mjs from the server's OpenAPI document. Do not edit.",
  "",
  "/** One operation of the API. `live` operations can be opened as a stream of `Result` values. */",
  "export interface Operation<Args, Result, Live extends boolean> {",
  "  readonly name: string;",
  "  readonly method: string;",
  "  readonly path: string;",
  "  readonly live: Live;",
  "  readonly mediaTypes: readonly string[];",
  "  /** Type carriers only; never set at run time. */",
  "  readonly __args?: Args;",
  "  readonly __result?: Result;",
  "}",
  "",
];

// Component schemas the operations refer to, and the ones those refer to in turn.
const emitted = new Set();

for (let pending = [...used]; pending.length > 0; pending = [...used].filter(name => !emitted.has(name))) {
  for (const name of pending.sort()) {
    emitted.add(name);
    lines.push(`export type ${name} = ${toType(document.components.schemas[name])};`, "");
  }
}

lines.push("export interface Api {", ...entries, "}", "");
console.log(lines.join("\n"));
